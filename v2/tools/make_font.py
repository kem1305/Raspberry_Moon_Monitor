#!/usr/bin/env python3
"""Rasterise DejaVu Sans into anti-aliased (4 bit) bitmap fonts -> firmware/src/font_data.h"""
import os
from PIL import ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "firmware", "src", "font_data.h")
DIR = "/usr/share/fonts/truetype/dejavu/"
CHARS = "".join(chr(c) for c in range(32, 127)) + "°ºª·áàâãéêíóôõúüçÁÀÂÃÉÊÍÓÔÕÚÇ↑↓–"
FONTS = [("FONT_S", "DejaVuSans.ttf", 14), ("FONT_M", "DejaVuSans.ttf", 17),
         ("FONT_B", "DejaVuSans-Bold.ttf", 18), ("FONT_XL", "DejaVuSans-Bold.ttf", 30)]

out = ["// Generated by tools/make_font.py from DejaVu Sans (Bitstream Vera licence) - do not edit.",
       "#pragma once", "#include <stdint.h>", "",
       "struct Glyph { uint16_t code; uint16_t offset; uint8_t w, h; int8_t xoff, yoff; uint8_t adv; };",
       "struct Font { const Glyph* glyphs; uint16_t count; const uint8_t* data; uint8_t ascent, height; };", ""]
for name, file, size in FONTS:
    font = ImageFont.truetype(DIR + file, size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for ch in sorted(set(CHARS)):
        mask = font.getmask(ch, mode="L")
        w, h = mask.size
        bbox = font.getbbox(ch)                     # (x0, y0, x1, y1) relative to the ascender line
        adv = round(font.getlength(ch))
        xoff, yoff = (bbox[0], bbox[1]) if w and h else (0, 0)
        px = bytes(mask) if w and h else b""
        off = len(data)
        nib = [min(15, (p + 8) // 17) for p in px]
        if len(nib) % 2: nib.append(0)
        data += bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        glyphs.append((ord(ch), off, w, h, xoff, yoff, adv))
    assert len(data) < 65536
    out.append("static const uint8_t %s_DATA[] = {" % name)
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append("static const Glyph %s_GLYPHS[] = {" % name)
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append("static const Font %s = { %s_GLYPHS, %d, %s_DATA, %d, %d };" % (name, name, len(glyphs), name, ascent, ascent + descent))
    out.append("")
open(OUT, "w").write("\n".join(out))
print("wrote", OUT, os.path.getsize(OUT) // 1024, "KB source")
