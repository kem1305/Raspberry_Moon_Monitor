#!/usr/bin/env python3
"""Convert the NASA moon-phase frames (../assets/moon_/*.png, 240x240) into the firmware assets.

Outputs
  firmware/data/m/NNN.jpg       one JPEG per frame (LittleFS image, ~2 MB total)
  firmware/src/moon_frames.h    per-frame phase ("elongation") and terminator tilt tables

For every frame the illuminated fraction and the tilt of the terminator are *measured* from the
picture, so the firmware can pick the frame whose illumination matches the real Moon and rotate it so
that the bright limb points exactly where it does in the sky.
"""
import glob, math, os, sys
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(os.path.dirname(ROOT), "assets", "moon_")
OUT_IMG = os.path.join(ROOT, "firmware", "data", "m")
OUT_H = os.path.join(ROOT, "firmware", "src", "moon_frames.h")
QUALITY = 88

files = sorted(glob.glob(os.path.join(SRC, "*.png")))
n = len(files)
assert n > 100, "frames not found"
yy, xx = np.mgrid[0:240, 0:240]
X = xx - 119.5
Y = 119.5 - yy
disc = np.hypot(X, Y) < 117

k = np.zeros(n)
ang = np.full(n, np.nan)
os.makedirs(OUT_IMG, exist_ok=True)
for old in glob.glob(os.path.join(OUT_IMG, "*.jpg")):
    os.remove(old)
total = 0
for i, f in enumerate(files):
    im = Image.open(f).convert("RGB")
    assert im.size == (240, 240)
    a = np.asarray(im.convert("L")).astype(float)
    lit = (a > 30) & disc
    k[i] = lit.sum() / disc.sum()
    if 0.03 < k[i] < 0.90:
        ang[i] = math.degrees(math.atan2(-(lit * X).sum(), (lit * Y).sum()))   # CCW from "up"
    out = os.path.join(OUT_IMG, "%03d.jpg" % i)
    im.save(out, "JPEG", quality=QUALITY, optimize=True, subsampling=2)
    total += os.path.getsize(out)

# --- phase: 0..360 "elongation" such that illum = (1-cos e)/2, waxing first -------------------
ifull = int(np.argmax(np.convolve(k, np.ones(5) / 5, mode="same")))
e = np.degrees(np.arccos(np.clip(1 - 2 * k, -1, 1)))
e[ifull:] = 360 - e[ifull:]
# the measurement saturates near new/full: replace those by a straight-line fit of the reliable part
idx = np.arange(n)
good = (k > 0.03) & (k < 0.97)
slope, icpt = np.polyfit(idx[good], e[good], 1)
lin = slope * idx + icpt
e = np.where(good, e, lin)
e = np.maximum.accumulate(np.clip(e, 0, 360))          # monotonic
# --- tilt of the frame's "north" (perpendicular to its bright limb), CCW from up ---------------
north = np.where(idx < ifull, ang + 90, ang - 90)
ok = ~np.isnan(north)
north = np.interp(idx, idx[ok], north[ok])              # bridge new/full gaps
north = np.convolve(np.pad(north, 3, mode="edge"), np.ones(7) / 7, mode="valid")

with open(OUT_H, "w") as h:
    h.write("// Generated by tools/build_assets.py - do not edit.\n#pragma once\n#include <stdint.h>\n\n")
    h.write("#define MOON_FRAME_COUNT %d\n\n" % n)
    h.write("// phase of each frame, centi-degrees (0 new, 9000 first quarter, 18000 full, 27000 last quarter)\n")
    h.write("static const uint16_t MOON_FRAME_ELONG[MOON_FRAME_COUNT] = {\n")
    for r in range(0, n, 12):
        h.write("  " + ",".join("%d" % round(v * 100) for v in e[r:r + 12]) + ",\n")
    h.write("};\n\n// direction of each frame's lunar north, tenths of a degree counter-clockwise from image-up\n")
    h.write("static const int8_t MOON_FRAME_NORTH[MOON_FRAME_COUNT] = {\n")
    for r in range(0, n, 16):
        h.write("  " + ",".join("%d" % round(v * 10) for v in north[r:r + 16]) + ",\n")
    h.write("};\n")
print("frames: %d  full moon at #%d  jpeg total: %.2f MB" % (n, ifull, total / 1e6))
print("phase step: %.2f deg/frame (fit), tilt range %.1f..%.1f deg" % (slope, north.min(), north.max()))
